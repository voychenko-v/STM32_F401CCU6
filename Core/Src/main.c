static void usb_log(const char *str)
{
    uint32_t t0 = HAL_GetTick();
    while (CDC_Transmit_FS((uint8_t *)str, strlen(str)) == USBD_BUSY)
    {
        if (HAL_GetTick() - t0 > 20) break;
    }
}


static void uart_send(const char *str)
{
    HAL_UART_Transmit(&huart1, (uint8_t *)str, strlen(str), 100);
}


void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
    if (huart->Instance == USART1)
    {
        if (rx_byte == '\n')
        {
            if (!line_ready)
            {
                rx_line[rx_len] = '\0';
                strcpy(ready_line, rx_line);
                line_ready = 1;
            }
            rx_len = 0;
        }
        else if (rx_byte != '\r' && rx_len < RX_LINE_MAX - 1)
        {
            rx_line[rx_len++] = (char)rx_byte;
        }

        HAL_UART_Receive_IT(&huart1, &rx_byte, 1);
    }
}

void HAL_UART_ErrorCallback(UART_HandleTypeDef *huart)
{
    if (huart->Instance == USART1)
    {
        HAL_UART_Receive_IT(&huart1, &rx_byte, 1);
    }
}

static uint8_t button_pressed_event(void)
{
    static uint8_t last_raw = 1;
    static uint8_t stable = 1;
    static uint32_t last_change = 0;

    uint8_t raw = (HAL_GPIO_ReadPin(GPIOA, GPIO_PIN_0) == GPIO_PIN_SET);
    uint32_t now = HAL_GetTick();

    if (raw != last_raw) {
        last_raw = raw;
        last_change = now;
    }

    if ((now - last_change) >= DEBOUNCE_MS && raw != stable) {
        stable = raw;
        if (stable == 0) return 1;
    }
    return 0;
}
